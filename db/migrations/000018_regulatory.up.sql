-- Regulatory reporting: farm master data for the authorities' fertilization records (ENNI in
-- Niedersachsen, ENDO in Schleswig-Holstein), the 170 kg N organic farm data, and the land-use
-- codes (Nutzungscodes) of the subsidy application (Agrarantrag).

ALTER TABLE farms
  -- Registration number of the holding (Betriebsnummer, e.g. 276 + 12 digits in NI and SH).
  ADD COLUMN holding_number text CHECK (holding_number ~ '^[0-9]{6,20}$'),
  -- First month of the fertilizer year (Düngejahr), JANUAR for the calendar year.
  ADD COLUMN fertilizer_year_start text NOT NULL DEFAULT 'JANUAR' CHECK (fertilizer_year_start IN (
    'JANUAR', 'FEBRUAR', 'MAERZ', 'APRIL', 'MAI', 'JUNI', 'JULI', 'AUGUST', 'SEPTEMBER', 'OKTOBER', 'NOVEMBER', 'DEZEMBER')),
  ADD COLUMN organic_certified boolean NOT NULL DEFAULT false,
  -- Format-specific master data the authorities ask for (Boden-Klima-Raum, Naturraum, contact
  -- addresses, crop code overrides); validated by the API.
  ADD COLUMN regulatory jsonb NOT NULL DEFAULT '{}'::jsonb;

-- Organic N brought onto or taken off the farm and livestock, per farm and fertilizer year, for the
-- 170 kg N/ha limit (DüV §6 Abs. 4). Entered by the user; agmeo keeps no livestock records.
CREATE TABLE n170_inputs (
  organization_id uuid NOT NULL,
  farm_id         uuid NOT NULL,
  year            smallint NOT NULL CHECK (year BETWEEN 1990 AND 2200),
  data            jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (farm_id, year),
  FOREIGN KEY (organization_id, farm_id) REFERENCES farms (organization_id, id) ON DELETE CASCADE
);
CREATE TRIGGER n170_inputs_updated_at BEFORE UPDATE ON n170_inputs
  FOR EACH ROW EXECUTE FUNCTION app.set_updated_at();

-- Harmonised land-use codes of the subsidy application (shared reference data), from
-- AGVOLUTION/agmeo (scripts/generate-land-use-codes.py). `agmeo_crop_key` links a code to the crop
-- vocabulary of the export library.
CREATE TABLE land_use_codes (
  code            text PRIMARY KEY,
  name_de         text NOT NULL,
  agmeo_crop_key  text,
  -- Landscape features, fallow and set-aside bring no harvest.
  productive      boolean NOT NULL
);

-- The code a crop is declared with by default; a crop cycle may name another one.
ALTER TABLE crops ADD COLUMN land_use_code text REFERENCES land_use_codes (code);
ALTER TABLE crop_cycles ADD COLUMN land_use_code text REFERENCES land_use_codes (code);

