/** Ported from agmeo `src/lib/federalExport/harmonie-export/st/serializers/dbe.ts`. */

import type { StDbeRow } from '../types.js';
import type { StColumn } from './format.js';
import {
  betriebCells,
  schlagCells,
  serializeStRow,
  ST_BETRIEB_COLUMNS,
  ST_SCHLAG_COLUMNS,
} from './format.js';

const decimal = (name: string): StColumn => ({ name, format: 'decimal' });

/** Column names follow the LLG spec verbatim, including `P205_Gehalt` (sic) and the wrapped `Stickstoffnachlieferung WRWGH`. */
export const DBE_COLUMNS: readonly StColumn[] = [
  ...ST_BETRIEB_COLUMNS,
  ...ST_SCHLAG_COLUMNS,
  { name: 'BG', format: 'integer' },
  { name: 'AZ', format: 'integer' },
  { name: 'VF', format: 'text' },
  { name: 'VF_Nr', format: 'text' },
  { name: 'Zwfr', format: 'text' },
  { name: 'Zwfr_Nr', format: 'text' },
  { name: 'HF', format: 'text' },
  { name: 'HF_Nr', format: 'text' },
  decimal('N_Bedarfswert_DueV'),
  decimal('ErtragFM_DueV'),
  decimal('ErtragFM_Betrieb'),
  decimal('ErtragFM_Diff'),
  decimal('ErtragTM_DueV'),
  decimal('ErtragTM_Betrieb'),
  decimal('ErtragTM_Diff'),
  decimal('RP_DueV'),
  decimal('RP_Betrieb'),
  decimal('RP_Diff'),
  decimal('Nmin_gesamt'),
  decimal('Nmin_0_30'),
  decimal('Nmin_30_60'),
  decimal('Nmin_60_90'),
  { name: 'DatenherkunftNmin_0_60', format: 'text' },
  { name: 'DatenherkunftNmin_60_90', format: 'text' },
  decimal('ZuAbN_Ertrag_Diff'),
  decimal('ZuAbN_RP_Diff'),
  decimal('AbN_Nachl_Boden'),
  decimal('AbN_Nachl_OD'),
  decimal('AbN_Nachl_Leg'),
  decimal('AbN_VF'),
  decimal('AbN_Zwfr'),
  decimal('ZuN_Abdeckung'),
  decimal('ZuN_nachtraeglich'),
  decimal('BedarfN_berechnet'),
  decimal('Stickstoffnachlieferung WRWGH'),
  decimal('P205_Gehalt'),
  { name: 'P_AnalyseDatum', format: 'date' },
  { name: 'P_Methode', format: 'text' },
];

export function serializeDbeRow(row: StDbeRow): string {
  return serializeStRow(DBE_COLUMNS, [
    ...betriebCells(row),
    ...schlagCells(row),
    row.bg,
    row.az,
    row.vf,
    row.vfNr,
    row.zwfr,
    row.zwfrNr,
    row.hf,
    row.hfNr,
    row.nBedarfswertDuev,
    row.ertragFmDuev,
    row.ertragFmBetrieb,
    row.ertragFmDiff,
    row.ertragTmDuev,
    row.ertragTmBetrieb,
    row.ertragTmDiff,
    row.rpDuev,
    row.rpBetrieb,
    row.rpDiff,
    row.nminGesamt,
    row.nmin030,
    row.nmin3060,
    row.nmin6090,
    row.datenherkunftNmin060,
    row.datenherkunftNmin6090,
    row.zuAbNErtragDiff,
    row.zuAbNRpDiff,
    row.abNNachlBoden,
    row.abNNachlOd,
    row.abNNachlLeg,
    row.abNVf,
    row.abNZwfr,
    row.zuNAbdeckung,
    row.zuNNachtraeglich,
    row.bedarfNBerechnet,
    row.stickstoffnachlieferungWrwgh,
    row.p2o5Gehalt,
    row.pAnalyseDatum,
    row.pMethode,
  ]);
}
